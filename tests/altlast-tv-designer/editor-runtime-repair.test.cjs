const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'pc-manager/tv-editor-runtime-repair-v02953.js'),'utf8');
const context={window:{},document:{readyState:'loading',addEventListener(){}},setTimeout,MutationObserver:function(){},requestAnimationFrame(){}};
context.window=context.window;
vm.runInNewContext(source,context);
const api=context.window.KCTVEditorRuntimeRepair;
assert.equal(api.version,'0.29.53');
let p={slides:[{id:'A'},{id:'B'},{id:'C'},{id:'D'}]};
assert.equal(api.reorder(p,'A',2,true),2);
assert.deepEqual(p.slides.map(x=>x.id),['B','C','A','D']);
p={slides:[{id:'A'},{id:'B'},{id:'C'},{id:'D'}]};
assert.equal(api.reorder(p,'D',1,false),1);
assert.deepEqual(p.slides.map(x=>x.id),['A','D','B','C']);

const unified=fs.readFileSync(path.join(root,'pc-manager/tv-unified-editor.js'),'utf8');
const inspector=fs.readFileSync(path.join(root,'pc-manager/tv-context-inspector-v02942.js'),'utf8');
const flags=fs.readFileSync(path.join(root,'shared/runtime-flags.js'),'utf8');
const pos=fs.readFileSync(path.join(root,'pos/app.js'),'utf8');
const clock=fs.readFileSync(path.join(root,'pos/time-clock-pos.js'),'utf8');
const index=fs.readFileSync(path.join(root,'pc-manager/index.html'),'utf8');
